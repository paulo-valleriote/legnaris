export type MessageKey = keyof typeof messages;

export type MessageValues = Readonly<Record<string, string | number>>;

export function message(key: MessageKey): string {
  return messages[key];
}

export function messageWith(key: MessageKey, values: MessageValues): string {
  return messages[key].replace(/\{(\w+)\}/g, (_match, name: string) => {
    const value = values[name];

    if (value === undefined) {
      throw new Error(`the copy "${key}" needs a value for "${name}"`);
    }

    return String(value);
  });
}

export type GenerationCopyKey =
  | 'generate.title'
  | 'generate.conceptLabel'
  | 'generate.conceptExample'
  | 'generation.resumeNotice'
  | 'generate.waiting'
  | 'generate.timedOut'
  | 'generate.alreadySaved'
  | 'generate.previewTitle'
  | 'generate.previewNote'
  | 'generate.lastKeep';

export function generationCopy(key: GenerationCopyKey, kind: SheetKind): string {
  return messages[`${key}.${kind}`];
}
