package mockscheck_test

import (
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"legnaris/scripts/ci/mockscheck"
)

func TestIssues(t *testing.T) {
	tests := []struct {
		name    string
		path    string
		content string
		want    []string
	}{
		{
			name:    "Happy path: a mock in mocks/ carries the generated header",
			path:    "backend/internal/sheet/mocks/mock_Service.go",
			content: "// Code generated by mockery. DO NOT EDIT.\n\npackage mocks\n\ntype MockService struct{}\n",
			want:    nil,
		},
		{
			name:    "Happy path: a plain source without mock types passes",
			path:    "backend/internal/sheet/service.go",
			content: "package sheet\n\ntype Service struct{}\n",
			want:    nil,
		},
		{
			name:    "Edge: a header separated from the package clause by imports",
			path:    "backend/internal/sheet/mocks/mock_Service.go",
			content: "// Code generated by mockery v2.53.5. DO NOT EDIT.\n\npackage mocks\n\nimport \"testing\"\n",
			want:    nil,
		},
		{
			name:    "Edge: a nested mocks directory is still a mocks directory",
			path:    "backend/internal/email/relay/mocks/mock_Publisher.go",
			content: "package mocks\n",
			want:    []string{"backend/internal/email/relay/mocks/mock_Publisher.go: mock file is missing the \"// Code generated ... DO NOT EDIT.\" header"},
		},
		{
			name:    "Edge: a non-struct Mock type outside mocks/ is allowed",
			path:    "backend/internal/sheet/service.go",
			content: "package sheet\n\ntype MockAnything int\n",
			want:    nil,
		},
		{
			name:    "Edge: a Mock interface outside mocks/ is allowed",
			path:    "backend/internal/sheet/service.go",
			content: "package sheet\n\ntype MockReader interface{ Read() }\n",
			want:    nil,
		},
		{
			name:    "Edge: a local Mock struct inside a function is allowed",
			path:    "backend/internal/sheet/service.go",
			content: "package sheet\n\nfunc f() {\n\ttype MockLocal struct{}\n\t_ = MockLocal{}\n}\n",
			want:    nil,
		},
		{
			name:    "Edge: an unparsable file is not reported",
			path:    "backend/internal/sheet/broken.go",
			content: "package sheet\n\ntype MockBroken struct {\n",
			want:    nil,
		},
		{
			name:    "Error: a mock file that lost its header is reported",
			path:    "backend/internal/sheet/mocks/mock_Service.go",
			content: "package mocks\n\ntype MockService struct{}\n",
			want:    []string{"backend/internal/sheet/mocks/mock_Service.go: mock file is missing the \"// Code generated ... DO NOT EDIT.\" header"},
		},
		{
			name:    "Error: a header after the package clause does not count",
			path:    "backend/internal/sheet/mocks/mock_Service.go",
			content: "package mocks\n\n// Code generated by mockery. DO NOT EDIT.\n",
			want:    []string{"backend/internal/sheet/mocks/mock_Service.go: mock file is missing the \"// Code generated ... DO NOT EDIT.\" header"},
		},
		{
			name:    "Error: a Mock struct outside mocks/ is reported",
			path:    "backend/internal/sheet/service_test.go",
			content: "package sheet\n\ntype MockRepository struct{}\n",
			want:    []string{"backend/internal/sheet/service_test.go: mock type declared outside a mocks/ directory: type MockRepository struct"},
		},
		{
			name:    "Error: a generic Mock struct outside mocks/ is reported",
			path:    "backend/internal/sheet/service.go",
			content: "package sheet\n\ntype MockHolder[T any] struct{ value T }\n",
			want:    []string{"backend/internal/sheet/service.go: mock type declared outside a mocks/ directory: type MockHolder struct"},
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			assert.Equal(t, tc.want, mockscheck.Issues(tc.path, []byte(tc.content)))
		})
	}
}

func TestIsMocksPath(t *testing.T) {
	tests := []struct {
		name string
		path string
		want bool
	}{
		{
			name: "Happy path: a file directly in mocks/",
			path: "backend/internal/sheet/mocks/mock_Service.go",
			want: true,
		},
		{
			name: "Edge: the mocks directory itself is not a file inside it",
			path: "backend/internal/sheet/mocks",
			want: false,
		},
		{
			name: "Edge: a path that only contains the word mocks",
			path: "backend/internal/mocksheet/service.go",
			want: false,
		},
		{
			name: "Edge: a file at the repository root",
			path: "main.go",
			want: false,
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			assert.Equal(t, tc.want, mockscheck.IsMocksPath(tc.path))
		})
	}
}

func TestMockeryPinned(t *testing.T) {
	tests := []struct {
		name    string
		gomod   string
		wantErr bool
	}{
		{
			name:  "Happy path: the tool directive pins a released version",
			gomod: "module legnaris\n\ngo 1.26.10\n\nrequire (\n\tgithub.com/vektra/mockery/v2 v2.53.5 // indirect\n)\n\ntool github.com/vektra/mockery/v2\n",
		},
		{
			name:  "Happy path: a tool block pins the same module",
			gomod: "module legnaris\n\nrequire (\n\tgithub.com/vektra/mockery/v2 v2.53.5\n)\n\ntool (\n\tgithub.com/vektra/mockery/v2\n)\n",
		},
		{
			name:    "Edge: another tool does not pin mockery",
			gomod:   "module legnaris\n\nrequire (\n\tgithub.com/vektra/mockery/v2 v2.53.5\n)\n\ntool github.com/vektra/mockery/v3\n",
			wantErr: true,
		},
		{
			name:    "Edge: a blank versionless requirement is not pinned",
			gomod:   "module legnaris\n\ntool github.com/vektra/mockery/v2\n",
			wantErr: true,
		},
		{
			name:    "Error: an empty go.mod is rejected",
			gomod:   "",
			wantErr: true,
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			err := mockscheck.MockeryPinned([]byte(tc.gomod))
			if tc.wantErr {
				require.ErrorIs(t, err, mockscheck.ErrMockeryUnpinned)
				return
			}
			require.NoError(t, err)
		})
	}
}
