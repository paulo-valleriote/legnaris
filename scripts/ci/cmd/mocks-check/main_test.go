package main

import (
	"bytes"
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

const pinnedGoMod = "module legnaris\n\ngo 1.26.10\n\nrequire (\n\tgithub.com/vektra/mockery/v2 v2.53.5 // indirect\n)\n\ntool github.com/vektra/mockery/v2\n"

func writeFile(t *testing.T, dir, name, content string) string {
	t.Helper()
	p := filepath.Join(dir, name)
	require.NoError(t, os.MkdirAll(filepath.Dir(p), 0o755))
	require.NoError(t, os.WriteFile(p, []byte(content), 0o644))
	return p
}

func TestRun(t *testing.T) {
	tests := []struct {
		name     string
		gomod    string
		files    map[string]string
		wantCode int
		wantOut  string
		wantErr  string
	}{
		{
			name:  "Happy path: pinned mockery and generated mocks pass",
			gomod: pinnedGoMod,
			files: map[string]string{
				"mocks/mock_Service.go":  "// Code generated by mockery. DO NOT EDIT.\n\npackage mocks\n\ntype MockService struct{}\n",
				"internal/sheet.go":      "package internal\n\ntype Service struct{}\n",
				"internal/sheet_test.go": "package internal\n",
			},
			wantCode: 0,
			wantOut:  "every mock carries the header",
		},
		{
			name:     "Edge: no Go files at all still checks the pin",
			gomod:    pinnedGoMod,
			files:    map[string]string{},
			wantCode: 0,
			wantOut:  "0 Go files",
		},
		{
			name:  "Error: a mock missing its header fails",
			gomod: pinnedGoMod,
			files: map[string]string{
				"mocks/mock_Service.go": "package mocks\n\ntype MockService struct{}\n",
			},
			wantCode: 1,
			wantErr:  "missing the \"// Code generated ... DO NOT EDIT.\" header",
		},
		{
			name:  "Error: a Mock struct outside mocks/ fails",
			gomod: pinnedGoMod,
			files: map[string]string{
				"internal/sheet_test.go": "package internal\n\ntype MockSheetService struct{}\n",
			},
			wantCode: 1,
			wantErr:  "mock type declared outside a mocks/ directory",
		},
		{
			name:     "Error: an unpinned mockery fails",
			gomod:    "module legnaris\n\ntool github.com/vektra/mockery/v2\n",
			files:    map[string]string{},
			wantCode: 1,
			wantErr:  "mockery is not pinned by the go.mod tool directive",
		},
		{
			name:     "Error: an unreadable Go file fails",
			gomod:    pinnedGoMod,
			files:    map[string]string{},
			wantCode: 1,
			wantErr:  "no such file or directory",
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			gomod := writeFile(t, dir, "go.mod", tc.gomod)
			var files []string
			for name, content := range tc.files {
				files = append(files, writeFile(t, dir, name, content))
			}
			if tc.wantErr == "no such file or directory" {
				files = append(files, filepath.Join(dir, "absent.go"))
			}

			var stdout, stderr bytes.Buffer
			code := run(gomod, files, &stdout, &stderr)
			require.Equal(t, tc.wantCode, code)
			assert.Contains(t, stdout.String(), tc.wantOut)
			assert.Contains(t, stderr.String(), tc.wantErr)
		})
	}
}

func TestRunWithoutGoMod(t *testing.T) {
	t.Run("Error: a missing go.mod fails fast", func(t *testing.T) {
		var stdout, stderr bytes.Buffer
		code := run(filepath.Join(t.TempDir(), "go.mod"), nil, &stdout, &stderr)
		require.Equal(t, 2, code)
		assert.Contains(t, stderr.String(), "no such file or directory")
	})
}
