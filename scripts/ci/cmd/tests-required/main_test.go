func TestRun(t *testing.T) {
	tests := []struct {
		name     string
		paths    string
		labels   string
		wantCode int
		wantOut  string
		wantErr  string
	}{
		{
			name:     "Happy path: a Go package and web source with test changes pass",
			paths:    "backend/internal/sheet/service.go\nbackend/internal/sheet/service_test.go\nweb/src/sheet/grid.tsx\nweb/src/test/sheet_grid.test.tsx\n",
			wantCode: 0,
			wantOut:  "every one that needs a test has one",
		},
		{
			name:     "Happy path: the escape hatch label skips the check",
			paths:    "backend/internal/sheet/service.go\n",
			labels:   `["no-tests:refactor"]`,
			wantCode: 0,
			wantOut:  "skipped by the \"no-tests:refactor\" label",
		},
		{
			name:     "Edge: an empty diff passes",
			paths:    "",
			wantCode: 0,
			wantOut:  "0 changed paths",
		},
		{
			name:     "Edge: unrelated paths do not trip the check",
			paths:    "README.md\n.github/workflows/ci.yml\nbackend/internal/sheet/mocks/mock_Service.go\n",
			wantCode: 0,
			wantOut:  "3 changed paths",
		},
		{
			name:     "Edge: a malformed label payload is not an escape hatch",
			paths:    "backend/internal/sheet/service.go\n",
			labels:   `["no-tests:refactor"`,
			wantCode: 1,
			wantErr:  "go backend/internal/sheet changed without a *_test.go change",
		},
		{
			name:     "Error: a Go package without a test change fails",
			paths:    "backend/internal/sheet/service.go\n",
			wantCode: 1,
			wantErr:  "go backend/internal/sheet changed without a *_test.go change",
		},
		{
			name:     "Error: a web source without a web test change fails",
			paths:    "web/src/sheet/grid.tsx\n",
			wantCode: 1,
			wantErr:  "web/src/ changed without a change under web/src/test/",
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			var stdout, stderr bytes.Buffer
			env := map[string]string{"PR_LABELS": tc.labels}
			code := run(strings.NewReader(tc.paths), &stdout, &stderr, func(key string) string {
				return env[key]
			})
			require.Equal(t, tc.wantCode, code)
			assert.Contains(t, stdout.String(), tc.wantOut)
			assert.Contains(t, stderr.String(), tc.wantErr)
		})
	}
}

func TestRunWritesTheExceptionToTheSummary(t *testing.T) {
	t.Run("Happy path: the exception lands in the step summary", func(t *testing.T) {
		summary := filepath.Join(t.TempDir(), "summary.md")
		require.NoError(t, os.WriteFile(summary, []byte("## CI\n"), 0o644))

		var stdout, stderr bytes.Buffer
		env := map[string]string{
			"PR_LABELS":           `["no-tests:refactor"]`,
			"GITHUB_STEP_SUMMARY": summary,
		}
		code := run(strings.NewReader("backend/internal/sheet/service.go\n"), &stdout, &stderr, func(key string) string {
			return env[key]
		})
		require.Equal(t, 0, code)

		content, err := os.ReadFile(summary)
		require.NoError(t, err)
		assert.Contains(t, string(content), "## CI")
		assert.Contains(t, string(content), testspair.ExceptionLabel)
	})

	t.Run("Edge: no summary path is harmless", func(t *testing.T) {
		var stdout, stderr bytes.Buffer
		code := run(strings.NewReader(""), &stdout, &stderr, func(string) string { return "" })
		require.Equal(t, 0, code)
		assert.NotContains(t, stderr.String(), "tests-required")
	})
}

func TestGeneratedFile(t *testing.T) {
	t.Run("Happy path: a generated file is recognised by its header", func(t *testing.T) {
		p := filepath.Join(t.TempDir(), "generated.go")
		require.NoError(t, os.WriteFile(p, []byte("// Code generated by mockery. DO NOT EDIT.\n\npackage mocks\n"), 0o644))
		assert.True(t, generatedFile(p))
	})

	t.Run("Edge: a plain file is not generated", func(t *testing.T) {
		p := filepath.Join(t.TempDir(), "plain.go")
		require.NoError(t, os.WriteFile(p, []byte("package sheet\n"), 0o644))
		assert.False(t, generatedFile(p))
	})

	t.Run("Edge: a test that embeds the header in a string literal is not generated", func(t *testing.T) {
		p := filepath.Join(t.TempDir(), "main_test.go")
		require.NoError(t, os.WriteFile(p, []byte("package main\n\nconst fixture = \"// Code generated by mockery. DO NOT EDIT.\\n\"\n"), 0o644))
		assert.False(t, generatedFile(p))
	})

	t.Run("Edge: a missing file is not generated", func(t *testing.T) {
		assert.False(t, generatedFile(filepath.Join(t.TempDir(), "absent.go")))
	})
}
