package main

import (
	"fmt"
	"testing"

	"github.com/stretchr/testify/assert"
)

func TestScanTS(t *testing.T) {
	tests := []struct {
		name string
		path string
		src  string
		want []string
	}{
		{
			name: "Edge: empty file",
			path: "sample.ts",
			src:  "",
		},
		{
			name: "Edge: comment markers in quoted strings",
			path: "sample.ts",
			src:  "const a = 'https://example.test';\nconst b = \"// not a comment\";\n",
		},
		{
			name: "Edge: comment markers in a template literal",
			path: "sample.ts",
			src:  "const a = `https://example.test // not a comment`;\n",
		},
		{
			name: "Edge: comment in a template expression",
			path: "sample.ts",
			src:  "const a = `value ${item /* why */}`;\n",
			want: []string{"1:/* why */"},
		},
		{
			name: "Edge: escaped slashes in a regex literal",
			path: "sample.ts",
			src:  "const a = /https?:\\/\\//;\nconst b = /[/*]/;\n",
		},
		{
			name: "Edge: regex literal after a return keyword",
			path: "sample.ts",
			src:  "function f() { return /https?:\\/\\//i; }\n",
		},
		{
			name: "Edge: division is not a regex literal",
			path: "sample.ts",
			src:  "const a = total / count; // real\n",
			want: []string{"1:// real"},
		},
		{
			name: "Edge: apostrophe in JSX text",
			path: "sample.tsx",
			src:  "const a = <p>Don't stop</p>;\n// real\n",
			want: []string{"2:// real"},
		},
		{
			name: "Edge: URL in JSX text and attributes",
			path: "sample.tsx",
			src:  "const a = <a href=\"https://example.test\">https://example.test</a>; // real\n",
			want: []string{"1:// real"},
		},
		{
			name: "Edge: comment inside a JSX expression",
			path: "sample.tsx",
			src:  "const a = <div>{/* block */}</div>; // real\n",
			want: []string{"1:/* block */", "1:// real"},
		},
		{
			name: "Edge: nested JSX keeps comments inside expressions",
			path: "sample.tsx",
			src:  "const a = <ul>{items.map((item) => <li key={item}>{/* row */}</li>)}</ul>; // real\n",
			want: []string{"1:/* row */", "1:// real"},
		},
		{
			name: "Edge: JSX fragment children",
			path: "sample.tsx",
			src:  "const a = <>{value /* in fragment */}</>; // real\n",
			want: []string{"1:/* in fragment */", "1:// real"},
		},
		{
			name: "Edge: generic arrow keeps following comments visible",
			path: "sample.tsx",
			src:  "const id = <T,>(value: T) => value;\n// real\n",
			want: []string{"2:// real"},
		},
		{
			name: "Edge: comparison operators in a ts file are not JSX",
			path: "sample.ts",
			src:  "const a = left < right; // real\n",
			want: []string{"1:// real"},
		},
		{
			name: "Edge: reference directive",
			path: "sample.ts",
			src:  "/// <reference lib=\"webworker\" />\n",
		},
		{
			name: "Edge: eslint disable without a reason",
			path: "sample.ts",
			src:  "// eslint-disable-next-line no-console\n",
		},
		{
			name: "Edge: block eslint disable without a reason",
			path: "sample.tsx",
			src:  "/* eslint-disable jsx-a11y/no-autofocus */\n",
		},
		{
			name: "Edge: prettier ignore",
			path: "sample.ts",
			src:  "// prettier-ignore\n",
		},
		{
			name: "Edge: ts expect error",
			path: "sample.ts",
			src:  "// @ts-expect-error the library lies\n",
		},
		{
			name: "Edge: generated file header skips every comment",
			path: "sample.ts",
			src:  "// Code generated by tool. DO NOT EDIT.\n\n// helper\nconst a = 1;\n",
		},
		{
			name: "Error: eslint disable with a reason suffix",
			path: "sample.ts",
			src:  "// eslint-disable-next-line no-console -- noisy in tests\n",
			want: []string{"1:// eslint-disable-next-line no-console -- noisy in tests"},
		},
		{
			name: "Error: block eslint disable with a reason suffix",
			path: "sample.ts",
			src:  "/* eslint-disable no-console -- noisy */\n",
			want: []string{"1:/* eslint-disable no-console -- noisy */"},
		},
		{
			name: "Error: plain line comment",
			path: "sample.ts",
			src:  "const a = 1;\n// rationale\n",
			want: []string{"2:// rationale"},
		},
		{
			name: "Error: block comment",
			path: "sample.ts",
			src:  "const a = 1;\n/* rationale */\n",
			want: []string{"2:/* rationale */"},
		},
		{
			name: "Happy path: only allowed directives",
			path: "sample.tsx",
			src:  "/// <reference lib=\"webworker\" />\n// eslint-disable-next-line no-control-regex\n// prettier-ignore\n// @ts-expect-error\n/* eslint-disable jsx-a11y/no-autofocus */\n",
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			got := scanTS(tc.path, []byte(tc.src))
			assert.Equal(t, tc.want, violationKeys(got))
		})
	}
}

func TestScanTSPositions(t *testing.T) {
	src := "const a = 1;\n\n  // here\n"
	got := scanTS("sample.ts", []byte(src))
	if assert.Len(t, got, 1) {
		assert.Equal(t, 3, got[0].Line)
		assert.Equal(t, 3, got[0].Column)
		assert.Equal(t, "sample.ts:3:3: // here", fmt.Sprint(got[0]))
	}
}
