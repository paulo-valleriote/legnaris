package main

import (
	"fmt"
	"testing"

	"github.com/stretchr/testify/assert"
)

func TestScanGo(t *testing.T) {
	tests := []struct {
		name string
		src  string
		want []string
	}{
		{
			name: "Edge: empty file",
			src:  "",
		},
		{
			name: "Edge: package clause only",
			src:  "package sample\n",
		},
		{
			name: "Edge: comment markers in an interpreted string",
			src:  "package sample\n\nvar a = \"// not a comment /* either */\"\n",
		},
		{
			name: "Edge: comment markers in a raw string",
			src:  "package sample\n\nvar a = `// not a comment /* either */`\n",
		},
		{
			name: "Edge: go embed directive",
			src:  "package sample\n\n//go:embed templates/*\nvar templates string\n",
		},
		{
			name: "Edge: go generate directive",
			src:  "package sample\n\n//go:generate mockery\n",
		},
		{
			name: "Edge: nolint directive",
			src:  "package sample\n\n//nolint:gocyclo // reason\nfunc f() {}\n",
		},
		{
			name: "Edge: generated file header skips every comment",
			src:  "// Code generated by mockery. DO NOT EDIT.\n\npackage mocks\n\n// helper does things\nfunc helper() {}\n",
		},
		{
			name: "Edge: block comment is a violation",
			src:  "package sample\n\n/* block */\n",
			want: []string{"3:/* block */"},
		},
		{
			name: "Edge: reference directive is not a Go directive",
			src:  "package sample\n\n/// <reference lib=\"x\" />\n",
			want: []string{"3:/// <reference lib=\"x\" />"},
		},
		{
			name: "Error: plain line comment",
			src:  "package sample\n\n// rationale\n",
			want: []string{"3:// rationale"},
		},
		{
			name: "Error: doc comment on an exported symbol",
			src:  "package sample\n\n// Thing is a thing.\ntype Thing struct{}\n",
			want: []string{"3:// Thing is a thing."},
		},
		{
			name: "Happy path: only allowed directives",
			src:  "//go:build linux\n\npackage sample\n\n//go:embed assets/*\nvar assets string\n\n//nolint\nfunc f() {}\n",
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			got := scanGo("sample.go", []byte(tc.src))
			assert.Equal(t, tc.want, violationKeys(got))
		})
	}
}

func violationKeys(violations []Violation) []string {
	if len(violations) == 0 {
		return nil
	}
	keys := make([]string, 0, len(violations))
	for _, violation := range violations {
		keys = append(keys, fmt.Sprintf("%d:%s", violation.Line, violation.Text))
	}
	return keys
}
