func TestRunExplicitFiles(t *testing.T) {
	dir := t.TempDir()
	clean := filepath.Join(dir, "clean.go")
	dirty := filepath.Join(dir, "dirty.ts")
	require.NoError(t, os.WriteFile(clean, []byte("package clean\n"), 0o600))
	require.NoError(t, os.WriteFile(dirty, []byte("const a = 1; // why\n"), 0o600))

	var stdout, stderr bytes.Buffer
	code := run([]string{"--", clean, dirty}, &stdout, &stderr)

	assert.Equal(t, 1, code)
	assert.Empty(t, stderr.String())
	assert.Contains(t, stdout.String(), dirty+":1:14: // why")
}

func TestRunCleanRepositoryTree(t *testing.T) {
	dir := t.TempDir()
	ok := filepath.Join(dir, "ok.tsx")
	require.NoError(t, os.WriteFile(ok, []byte("const a = <p>Don't</p>;\n"), 0o600))

	var stdout, stderr bytes.Buffer
	code := run([]string{ok}, &stdout, &stderr)

	assert.Zero(t, code)
	assert.Empty(t, stdout.String())
	assert.Empty(t, stderr.String())
}

