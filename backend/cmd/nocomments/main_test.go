func TestFilterScanTargets(t *testing.T) {
	tests := []struct {
		name    string
		tracked []string
		want    []string
	}{
		{
			name:    "Edge: empty repository",
			tracked: nil,
		},
		{
			name:    "Edge: no scan targets",
			tracked: []string{"README.md", "web/package.json", "scripts/dev.sh"},
		},
		{
			name: "Edge: excluded dependency directories",
			tracked: []string{
				"web/node_modules/pkg/index.ts",
				"vendor/lib/lib.go",
				"web/dist/assets/app.ts",
			},
		},
		{
			name:    "Edge: excluded name must be a whole path segment",
			tracked: []string{"backend/myvendor/lib.go", "web/src/distribution.ts"},
			want:    []string{filepath.FromSlash("backend/myvendor/lib.go"), filepath.FromSlash("web/src/distribution.ts")},
		},
		{
			name: "Happy path: Go and web source files are kept",
			tracked: []string{
				"backend/cmd/api.go",
				"web/src/app.tsx",
				"web/e2e/auth.spec.ts",
				"web/src/styles.css",
			},
			want: []string{
				filepath.FromSlash("backend/cmd/api.go"),
				filepath.FromSlash("web/src/app.tsx"),
				filepath.FromSlash("web/e2e/auth.spec.ts"),
			},
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			assert.Equal(t, tc.want, filterScanTargets(tc.tracked))
		})
	}
}

func TestRunDiscoversTrackedFiles(t *testing.T) {
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git is unavailable")
	}
	dir := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(dir, "main.go"), []byte("package main\n\n// violation\n"), 0o600))
	require.NoError(t, os.WriteFile(filepath.Join(dir, "ignored.md"), []byte("<!-- fine -->\n"), 0o600))
	require.NoError(t, exec.Command("git", "-C", dir, "init", "-q").Run())
	require.NoError(t, exec.Command("git", "-C", dir, "add", "main.go", "ignored.md").Run())
	t.Chdir(dir)

	var stdout, stderr bytes.Buffer
	code := run(nil, &stdout, &stderr)

	assert.Equal(t, 1, code)
	assert.Equal(t, "main.go:3:1: // violation\n", stdout.String())
}
